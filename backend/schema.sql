-- EventFlow: three connected tables
CREATE TABLE IF NOT EXISTS users (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    email TEXT NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    role TEXT NOT NULL CHECK (role IN ('organizer', 'admin')),
    active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS events (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organizer_id INTEGER NOT NULL REFERENCES users(id),
    title TEXT NOT NULL,
    description TEXT NOT NULL DEFAULT '',
    date TIMESTAMP NOT NULL,
    location TEXT NOT NULL,
    capacity INTEGER NOT NULL CHECK (capacity > 0),
    is_public BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS registrations (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id INTEGER NOT NULL REFERENCES events(id),
    participant_name TEXT NOT NULL,
    participant_email TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'active'
       CHECK (status IN ('active', 'cancelled'))
);

-- Stops duplicate active registrations even if two requests arrive together.
CREATE UNIQUE INDEX IF NOT EXISTS one_active_registration
    ON registrations (event_id, LOWER(participant_email))
    WHERE status = 'active';
